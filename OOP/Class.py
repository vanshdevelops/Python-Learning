class Employee:
    language = "Python" #This is class attribute
    salary = 2000000



Vansh = Employee() # This is object of class Employee or Instance Attribute
Vansh.name = "Vansh"
print(Vansh.salary, Vansh.language)

XYZ = Employee()
XYZ.name = "XYZ"
print(XYZ.salary, XYZ.language)


# Here names is object or Instance attribute and salary and language are class attributes.


   