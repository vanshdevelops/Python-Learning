# This is an example of a for loop in Python that iterates over a list and a tuple, printing each element. The first loop iterates over a list of integers, while the second loop iterates over a tuple of integers.

l = [1, 2, 66, 9898, 88]
for i in l:
    print(i)



t = (88, 99, 100, 500)
for i in t:
    print(i)
