a = int(input("enter first number: "))
b = int(input("enter second number "))

char = input("enter the operation you want to perform: ")

if char == "+":
    print(a+b)
if char == "-":
    print(a-b)
elif char == "*":
    print(a*b)
elif char == "%":
    print(a%b)
elif char == "/":
    print(a)    